// Generates src/data/assets.ts and src/data/products.ts from the sources of truth:
// tasks/reference/assets.json (ARM-02), docs/PRODUCTS.json (ARM-03) and scripts/image-sizes.json (gen-images.py).
import { readFileSync, writeFileSync } from 'node:fs'

const read = (p) => JSON.parse(readFileSync(new URL(p, import.meta.url), 'utf8'))
const write = (p, s) => writeFileSync(new URL(p, import.meta.url), s)
const union = (xs) => xs.map((x) => `'${x}'`).join(' | ')

const a = read('../../tasks/reference/assets.json')
const sizes = read('./image-sizes.json')
const images = Object.fromEntries(a.images.map((i) => [i.id, {
  id: i.id, src: `/img/${i.id}.webp`, alt: i.caption, credit: i.author, license: i.license,
  creditRequired: i.creditRequired, sourcePage: i.sourcePage, usedIn: i.usedIn,
  width: sizes[i.id][0], height: sizes[i.id][1],
}]))
const videos = Object.fromEntries(a.videos.map((v) => [v.id, {
  id: v.id, youtubeId: v.youtubeId, title: v.title, channel: v.channel, embed: v.embed, poster: v.poster, usedIn: v.usedIn,
}]))
write('../src/data/assets.ts', `// GENERATED by scripts/gen-data.mjs from tasks/reference/assets.json. Do not edit by hand (npm run gen).
export type ImageId = ${union(Object.keys(images))}
export type VideoId = ${union(Object.keys(videos))}
export interface ImageAsset { id: ImageId; src: string; alt: string; credit: string; license: string; creditRequired: boolean; sourcePage: string; usedIn: string; width: number; height: number }
export interface VideoAsset { id: VideoId; youtubeId: string; title: string; channel: string; embed: string; poster: string; usedIn: string }
const B = import.meta.env.BASE_URL
export const images: Record<ImageId, ImageAsset> = ${JSON.stringify(images, null, 2).replace(/"src": "\/(img\/[^"]+)"/g, '"src": B + "$1"')}
export const videos: Record<VideoId, VideoAsset> = ${JSON.stringify(videos, null, 2)}
`)

const p = read('../../docs/PRODUCTS.json')
// Not every board documents its LEDs; normalise so consumers can always map over leds
// Single-source notes live in one site-wide footer note, so inline [VERIFY] fragments are dropped from display text
const clean = (t) => t.replace(/\s*·\s*[^·]*\[VERIFY\]/g, '').replace(/\s*\[VERIFY\]/g, '')
const items = p.products.map((x) => ({ ...x, leds: x.leds ?? [], hotspots: x.hotspots.map((h) => ({ ...h, spec: clean(h.spec) })) }))
write('../src/data/products.ts', `// GENERATED by scripts/gen-data.mjs from docs/PRODUCTS.json (ARM-03). Do not edit by hand (npm run gen).
// Specs are real catalogue/datasheet values; open source conflicts are in \`verify\` / \`conflicts\` (not rendered).
export type ProductCode = ${union(items.map((x) => x.code))}
export type ProductLine = 'IA' | 'BA'
export interface Spec { label: string; value: string; unit: string; source: string; verify?: string }
export interface Hotspot { id: string; label: string; kind: string; spec: string }
export interface Product {
  code: ProductCode; slug: string; line: ProductLine; name: string; tagline: string; power: string
  interfaces: string[]; io: { di: number; do: number; ai: number; aiType: string | null }
  mcu: string | null; mounting: string; targets: string[]; datasheetUrl: string; datasheetKind: string
  specs: Spec[]; hotspots: Hotspot[]; leds: string[]; conflicts: string[]; tasmota: boolean; verified: boolean
}
export const productsMeta = ${JSON.stringify(p.meta, null, 2)}
export const products: Product[] = ${JSON.stringify(items, null, 2)}

/** Looks up a product by code or slug, case-insensitive ('IA015', 'ia015'). */
export function getProduct(code: string | undefined): Product | undefined {
  if (!code) return undefined
  const c = code.toLowerCase()
  return products.find((x) => x.slug === c || x.code.toLowerCase() === c)
}
`)
console.log('assets.ts:', a.images.length, 'images,', a.videos.length, 'videos · products.ts:', p.products.length, 'products')
